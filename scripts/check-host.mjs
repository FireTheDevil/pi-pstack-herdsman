import assert from 'node:assert/strict';
import { existsSync, readFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
const [piPath, herdsmanPath] = process.argv.slice(2);
if (!piPath || !herdsmanPath) throw new Error('Usage: node scripts/check-host.mjs <installed-pi-root> <installed-herdsman-root>');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const piRoot = resolve(piPath), host = resolve(herdsmanPath);
const semver = v => { const m = /^(\d+)\.(\d+)\.(\d+)(?:[-+].*)?$/.exec(v); if (!m) throw new Error(`Unparseable version: ${v}`); return m.slice(1, 4).map(Number); };
const cmp = (a, b) => { const x = semver(a), y = semver(b); for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i]; return 0; };
const inRange = (v, min, max) => cmp(v, min) >= 0 && cmp(v, max) < 0;
const version = JSON.parse(readFileSync(join(host, 'package.json'), 'utf8')).version;
assert.ok(inRange(version, '0.19.1', '0.27.0'), `pi-herdsman ${version} outside >=0.19.1 <0.27.0; revalidate documented backend contracts before upgrading`);
const piVersion = JSON.parse(readFileSync(join(piRoot, 'package.json'), 'utf8')).version;
assert.ok(inRange(piVersion, '1.0.2', '1.3.0'), `Pi ${piVersion} outside >=1.0.2 <1.3.0`);
const schema = readFileSync(join(host, 'docs/reference/agent-definition-schema.md'), 'utf8');
assert.match(schema, /active_agent name=/);
assert.match(readFileSync(join(host, 'dist/index.js'), 'utf8'), /--append-system-prompt", `<active_agent name="\$\{agent\.name\}"\/>`/, 'Herdsman must still append the <active_agent> marker the extension uses for leaf detection');
assert.match(schema, /bundled < project < global/);
assert.match(schema, /Unknown frontmatter fields fail validation/);
assert.match(schema, /exclusion wins over an allowlist/);
const api = readFileSync(join(host, 'docs/reference/agent.md'), 'utf8');
assert.match(api, /delegate_agent/);
assert.match(api, /continue_agent/);
assert.match(api, /available_tools/);
assert.match(api, /Each tool accepts only its operation's fields/);
const piLoader = join(piRoot, 'dist/core/extensions/loader.js');
if (!existsSync(piLoader)) throw new Error(`${piRoot} has no dist/ (compiled single-binary Pi?). Pass an npm-installed @earendil-works/pi-coding-agent package root.`);
const { loadExtensions } = await import(pathToFileURL(piLoader));
const { loadSkillsFromDir } = await import(pathToFileURL(join(piRoot, 'dist/core/skills.js')));
const tmp = join(root, '.pi-herdsman/tmp');
mkdirSync(tmp, { recursive: true });
const isolated = mkdtempSync(join(tmp, 'host-'));
try {
  const loaded = await loadExtensions([join(root, 'extensions/pstack-herdsman/index.ts')], isolated);
  assert.deepEqual(loaded.errors, []);
  assert.equal(loaded.extensions.length, 1);
  assert.deepEqual([...loaded.extensions[0].commands.keys()].sort(), ['poteto-mode', 'pstack-status', 'setup-pstack']);
  const skills = loadSkillsFromDir({ dir: join(root, 'skills'), source: 'local' });
  assert.equal(skills.skills.length, 50);
  assert.deepEqual(skills.diagnostics, []);
  assert.ok(skills.skills.every(s => s.disableModelInvocation));
  console.log(JSON.stringify({ piVersion, herdsmanVersion: version, extensionLoad: 'passed', skillsLoaded: 50, backendDocumentationContracts: 'passed', liveDelegation: false, definitionDiscoveryRuntime: 'not exercised' }));
} finally { rmSync(isolated, { recursive: true, force: true }); }
